CREATE TABLE IF NOT EXISTS marketplace.stg_marketplace_orders
(
    id                      UInt64,
    marketplace_seller_id   UInt64,
    order_id                UInt64,
    old_order_id            Nullable(Int64),
    type                    LowCardinality(String),
    status                  LowCardinality(Nullable(String)),
    business_state          LowCardinality(String),
    is_unmapped_status      UInt8,
    sub_total               Decimal(18, 4),
    discount_amount         Decimal(18, 4),
    shipping_amount         Decimal(18, 4),
    cod_charges             Decimal(18, 4),
    mgmt_fee                Decimal(18, 4),
    vas_total               Decimal(18, 4),
    grand_total             Decimal(18, 4),
    commission              Decimal(18, 4),
    commission_percentage   Decimal(18, 4),
    seller_total            Decimal(18, 4),
    cashback_earned         Decimal(18, 4),
    grand_total_refunded    Decimal(18, 4),
    net_merchandise         Decimal(38, 4),
    take_rate               Nullable(Float64),
    gmv_tie_out_gap         Decimal(38, 4),
    cycle_hours             Nullable(Int64),
    is_quarantined          UInt8,
    total_item_count        Int32,
    total_qty_ordered       Int32,
    created_at              Nullable(DateTime),
    updated_at              Nullable(DateTime),
    completed_at            Nullable(DateTime),
    expected_delivery_date  Nullable(DateTime),
    returned_at             Nullable(DateTime),
    created_date            Nullable(Date),
    completed_date          Nullable(Date),
    _extracted_at           DateTime,
    _version                DateTime64(3)
)
ENGINE = ReplacingMergeTree(_version)
ORDER BY id;

